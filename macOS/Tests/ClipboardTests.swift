import AppKit
import CryptoKit

@MainActor
enum ClipboardTests {
    static func clipboard(_ directory: URL) throws {
        let pb = Tests.board()
        defer { pb.releaseGlobally() }
        let reader = ClipboardAccess(pb)
        let writer = ClipboardAccess(pb)
        let rich = try Tests.richText()
        try writer.write(rich)
        try Tests.expect(try reader.read() == rich && writer.read() == nil, "富文本回填及自身来源识别")
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            let item = NSPasteboardItem()
            try Tests.expect(item.setString(try TestProject.source("App"), forType: .string) && item.setData(Data(), forType: .init(marker)), "准备隐私标记")
            pb.clearContents()
            try Tests.expect(pb.writeObjects([item]), "写入隐私标记")
            try Tests.expect(try reader.read() == nil, "跳过 \(marker)")
        }
        let files = Payload.files([TestProject.root.appendingPathComponent("README.md").path, directory.path])
        let fileEntry = Entry(id: "f", date: Date(), content: files.content)
        if case let .entries(matchedFiles, _) = HistorySearch.evaluate([fileEntry], query: "readme tests-"),
           case let .entries(unmatchedFiles, _) = HistorySearch.evaluate([fileEntry], query: "readme missing-file") {
            try Tests.expect(matchedFiles.map(\.id) == ["f"] && unmatchedFiles.isEmpty, "跨文件路径匹配所有关键词")
        } else { throw AppError("文件搜索应返回记录列表") }
        try writer.write(files)
        try Tests.expect(try reader.read() == files, "文件和目录回填")
        try Tests.rejects("恢复不存在的文件") { try writer.write(.files([directory.appendingPathComponent("missing").path])) }
        try Tests.expect(try reader.read() == files, "文件缺失时保留剪贴板")
        let picture = try Tests.icon()
        try writer.write(picture)
        try Tests.expect(try reader.read() == picture, "逐字节恢复 PNG")
        guard case let .image(png, width, height) = picture, let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation
        else { throw AppError("项目图标无法转成 TIFF。") }
        pb.clearContents()
        try Tests.expect(pb.setData(tiff, forType: .tiff), "写入真实 TIFF")
        guard case let .image(converted, w, h)? = try reader.read() else { throw AppError("无法转为 PNG。") }
        try Tests.expect((w, h) == (width, height) && converted.starts(with: png.prefix(8)), "TIFF 转换 PNG 并保留尺寸")
    }

    static func largeHTML(_ directory: URL) throws {
        let url = directory.appendingPathComponent("history.db")
        let key = SymmetricKey(size: .bits256)
        let store = try HistoryStore(url: url, key: key)
        let pb = Tests.board()
        defer { pb.releaseGlobally() }
        let reader = ClipboardAccess(pb)
        let icon = try Data(contentsOf: TestProject.icon)
        let tag = "<img src=\"data:image/png;base64,\(icon.base64EncodedString())\">"
        let html = Data(String(repeating: tag, count: 16 * 1024 * 1024 / tag.utf8.count + 1).utf8)
        let payload = Payload.text("ClipNest 图标", html: html)
        try ClipboardAccess(pb).write(payload)
        try reader.capture(in: store)
        let reopened = try HistoryStore(url: url, key: key)
        guard let entry = try reopened.load().first else { throw AppError("大段 HTML 未收录。") }
        let restored = try reopened.payload(for: entry.id)
        try Tests.expect(restored == payload, "大于 16 MiB 的 HTML 跨重启完整恢复")
        try reader.write(restored, preservingChangesIn: reopened)
        try Tests.expect(pb.data(forType: .html) == html, "完整回填大段 HTML")
    }

    static func lockedCapture(_ directory: URL) throws {
        let url = directory.appendingPathComponent("history.db")
        let store = try HistoryStore(url: url, key: SymmetricKey(size: .bits256))
        let db = try HistoryDatabase(url)
        let pb = Tests.board()
        defer { pb.releaseGlobally() }
        let writer = ClipboardAccess(pb), reader = ClipboardAccess(pb)
        let text = try TestProject.source("App")
        let rich = try Tests.richText()
        try writer.write(.text(text))
        let sequence = pb.changeCount
        try db.exec("BEGIN IMMEDIATE")
        try Tests.rejects("保存失败中止回填") { try reader.write(rich, preservingChangesIn: store) }
        try db.exec("ROLLBACK")
        try Tests.expect(pb.changeCount == sequence && pb.string(forType: .string) == text && reader.handledSequence != sequence,
                   "写锁冲突后保留剪贴板及待收录版本")
        try reader.write(rich, preservingChangesIn: store)
        try Tests.expect(try store.load().first?.content == .text(text) && writer.read() == rich,
                   "释放写锁后保存同一版本并回填")
    }

    static func oldestCopy(_ directory: URL) throws {
        let url = directory.appendingPathComponent("history.db")
        let key = SymmetricKey(size: .bits256)
        let store = try HistoryStore(url: url, key: key)
        let rich = try Tests.richText()
        let oldest = try store.save(rich)
        let lines = Set(try TestProject.source("App").split(separator: "\n").map(String.init)).sorted()
        for line in lines.prefix(store.historyLimit - 1) { _ = try store.save(.text(line)) }
        try Tests.expect(store.entries.count == store.historyLimit && store.entries.last?.id == oldest.id, "最旧的富文本位于淘汰位置")
        let pb = Tests.board()
        defer { pb.releaseGlobally() }
        let reader = ClipboardAccess(pb), external = ClipboardAccess(pb)
        let pending = Payload.text(try TestProject.source("HistorySearch"))
        try external.write(pending)
        guard case let .text(text) = oldest.content else { throw AppError("应选中待回填的富文本。") }
        try store.withRetainedRecord(oldest.id) {
            try reader.write(.text(text), preservingChangesIn: store)
            try store.recordUse(of: oldest)
        }
        try Tests.expect(try external.read() == .text(text), "复制为纯文本移除回填内容的 HTML 和 RTF")
        let reopened = try HistoryStore(url: url, key: key)
        let entries = try reopened.load()
        try Tests.expect(entries.count == reopened.historyLimit &&
                   entries.prefix(2).map(\.id) == [oldest.id, HistoryStore.fingerprint(pending)], "历史保留刚回填和刚收录的内容")
        try Tests.expect(try reopened.payload(for: oldest.id) == rich, "临时淘汰后原 HTML 和 RTF 仍可恢复")
    }
}
